#!/usr/bin/env node
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { existsSync, writeFileSync } from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(scriptDir, '..')
const defaultDatabase = path.join(
  os.homedir(),
  'git/data-ai/learning/signal-workspace/signal/data/digest.sqlite',
)
const outputPath = path.join(repoRoot, 'src/data/readingData.ts')

function parseArgs(argv) {
  const options = {
    database: process.env.SIGNAL_DIGEST_DB ?? defaultDatabase,
    dryRun: false,
    limit: 60,
  }

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index]
    if (arg === '--dry-run') options.dryRun = true
    else if (arg === '--limit') {
      options.limit = Number.parseInt(argv[index + 1] ?? '', 10)
      index += 1
    } else if (arg === '--database') {
      options.database = path.resolve(argv[index + 1] ?? '')
      index += 1
    } else {
      throw new Error(`Unknown argument: ${arg}`)
    }
  }

  if (!Number.isInteger(options.limit) || options.limit < 1 || options.limit > 500) {
    throw new Error('--limit must be an integer between 1 and 500')
  }
  return options
}

function queryBookmarkedItems(database, limit) {
  const query = `
    SELECT
      title,
      canonical_url AS href,
      source_name AS source,
      author,
      COALESCE(published_at, bookmarked_updated_at, first_seen_at) AS date,
      COALESCE(NULLIF(tldr, ''), NULLIF(excerpt, ''), '') AS blurb,
      image_url AS imageSrc,
      tags,
      curated_category AS curatedCategory
    FROM items
    WHERE bookmarked = 1
      AND duplicate_of_item_id IS NULL
    ORDER BY COALESCE(bookmarked_updated_at, last_seen_at) DESC
    LIMIT ${limit};
  `
  const json = execFileSync('sqlite3', ['-readonly', '-json', database, query], {
    encoding: 'utf8',
    maxBuffer: 10 * 1024 * 1024,
  })
  return JSON.parse(json || '[]')
}

function countBookmarkedItems(database) {
  const value = execFileSync(
    'sqlite3',
    [
      '-readonly',
      database,
      'SELECT COUNT(*) FROM items WHERE bookmarked = 1 AND duplicate_of_item_id IS NULL;',
    ],
    { encoding: 'utf8' },
  )
  return Number.parseInt(value.trim(), 10)
}

function slugify(value) {
  return value
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 64)
}

function normalizeDate(value) {
  if (!value) return ''
  const parsed = new Date(value)
  return Number.isNaN(parsed.valueOf())
    ? String(value).slice(0, 10)
    : parsed.toISOString().slice(0, 10)
}

function firstTag(tags) {
  try {
    const parsed = JSON.parse(tags ?? '[]')
    return Array.isArray(parsed) ? String(parsed[0] ?? '') : ''
  } catch {
    return ''
  }
}

function toReadingItem(row) {
  const hash = createHash('sha256').update(row.href).digest('hex').slice(0, 8)
  const tag = row.curatedCategory || firstTag(row.tags) || row.source
  return {
    id: `${slugify(row.title) || 'reading'}-${hash}`,
    title: row.title,
    date: normalizeDate(row.date),
    href: row.href,
    tag,
    source: row.source,
    ...(row.author ? { author: row.author } : {}),
    ...(row.blurb ? { blurb: row.blurb.trim() } : {}),
    ...(row.imageSrc ? { imageSrc: row.imageSrc } : {}),
  }
}

function formatModule(items) {
  return `/**
 * Generated from Signal bookmarks by:
 *   node scripts/sync-signal-reading.mjs
 *
 * Do not edit this file by hand.
 */
export type ReadingItem = {
  id: string
  title: string
  /** ISO calendar date YYYY-MM-DD. */
  date: string
  href: string
  tag: string
  source: string
  author?: string
  blurb?: string
  imageSrc?: string
}

export const readingItems: ReadingItem[] = ${JSON.stringify(items, null, 2)}
`
}

function main() {
  const options = parseArgs(process.argv.slice(2))
  if (!existsSync(options.database)) {
    throw new Error(`Signal digest database not found: ${options.database}`)
  }

  const candidates = countBookmarkedItems(options.database)
  const rows = queryBookmarkedItems(options.database, options.limit)
  const items = rows.map(toReadingItem)
  const generated = formatModule(items)

  if (options.dryRun) {
    console.log(`WOULD WRITE ${path.relative(repoRoot, outputPath)}`)
    console.log(generated)
  } else {
    writeFileSync(outputPath, generated)
    console.log(`WROTE ${path.relative(repoRoot, outputPath)}`)
  }
  console.log(JSON.stringify({ candidates, emitted: items.length, limit: options.limit }))
}

try {
  main()
} catch (error) {
  console.error(error instanceof Error ? error.message : error)
  process.exitCode = 1
}
